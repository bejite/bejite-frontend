export const currencyLabelFromCode = (code, options = CURRENCY_OPTIONS) => {
  if (!code) return "";
  const trimmed = String(code).trim();
  const byParen = options.find((opt) => opt.includes(`(${trimmed})`));
  if (byParen) return byParen;
  return options.find((opt) => opt.toLowerCase().includes(trimmed.toLowerCase())) || trimmed;
};

export const currencyCodeFromLabel = (label) =>
  label?.match(/\(([^)]+)\)$/)?.[1] || String(label || "").trim();
